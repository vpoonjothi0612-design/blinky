"""Vehicle Event Data Structure.

Represents line-crossing events (ENTRY / EXIT) generated by the vehicle tracking system.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Dict, List, Literal, Optional, Tuple, Any

try:
    from src.view_classification import (
        VEHICLE_CAPTURE_ANGLES,
        normalize_angle_images,
        normalize_confidence,
        normalize_vehicle_angle,
    )
except ModuleNotFoundError:
    from view_classification import (
        VEHICLE_CAPTURE_ANGLES,
        normalize_angle_images,
        normalize_confidence,
        normalize_vehicle_angle,
    )

DirectionType = Literal["ENTRY", "EXIT", "NONE"]


@dataclass
class VehicleEvent:
    """Structured representation of a vehicle entry or exit event."""

    event_id: str
    track_id: int
    vehicle_type: str
    direction: DirectionType
    confidence: float
    timestamp: str
    frame_index: int
    bbox: List[int]
    view_angle: str = "UNKNOWN"
    view_angle_confidence: Optional[float] = None
    angle_images: Dict[str, str] = field(default_factory=dict)

    @property
    def frame_idx(self) -> int:
        """Backward-compatible property for frame index."""
        return self.frame_index

    @classmethod
    def create(
        cls,
        track_id: int,
        vehicle_type: str,
        direction: DirectionType,
        confidence: float,
        bbox: Tuple[int, int, int, int] | List[int],
        frame_index: Optional[int] = None,
        frame_idx: Optional[int] = None,
        event_id: Optional[str] = None,
        timestamp: Optional[str] = None,
        view_angle: object = "UNKNOWN",
        view_angle_confidence: object = None,
        angle_images: object = None,
    ) -> VehicleEvent:
        """Factory method to construct a VehicleEvent with unique event_id and ISO-8601 UTC timestamp."""
        f_idx = frame_index if frame_index is not None else (frame_idx if frame_idx is not None else 0)
        ts = timestamp or datetime.now(timezone.utc).isoformat()
        eid = event_id or f"evt_{uuid.uuid4().hex[:12]}"
        b_list = [int(v) for v in bbox]
        normalized_view_angle = normalize_vehicle_angle(view_angle)

        return cls(
            event_id=eid,
            track_id=int(track_id),
            vehicle_type=str(vehicle_type).lower(),
            direction=direction,
            confidence=round(float(confidence), 4),
            timestamp=ts,
            frame_index=int(f_idx),
            bbox=b_list,
            view_angle=normalized_view_angle,
            view_angle_confidence=normalize_confidence(view_angle_confidence) if normalized_view_angle != "UNKNOWN" else None,
            angle_images=normalize_angle_images(angle_images, VEHICLE_CAPTURE_ANGLES),
        )

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> VehicleEvent:
        """Reconstructs VehicleEvent instance from a dictionary."""
        view_angle = normalize_vehicle_angle(data.get("view_angle"))
        return cls(
            event_id=data["event_id"],
            track_id=int(data["track_id"]),
            vehicle_type=str(data["vehicle_type"]).lower(),
            direction=data["direction"],
            confidence=round(float(data["confidence"]), 4),
            timestamp=data["timestamp"],
            frame_index=int(data.get("frame_index", data.get("frame_idx", 0))),
            bbox=[int(x) for x in data["bbox"]],
            view_angle=view_angle,
            view_angle_confidence=normalize_confidence(data.get("view_angle_confidence")) if view_angle != "UNKNOWN" else None,
            angle_images=normalize_angle_images(data.get("angle_images"), VEHICLE_CAPTURE_ANGLES),
        )

    def to_dict(self) -> Dict[str, Any]:
        """Converts event to standard JSON-serializable dictionary."""
        view_angle = normalize_vehicle_angle(self.view_angle)
        return {
            "event_id": self.event_id,
            "track_id": self.track_id,
            "vehicle_type": self.vehicle_type,
            "direction": self.direction,
            "confidence": round(float(self.confidence), 4),
            "timestamp": self.timestamp,
            "frame_index": self.frame_index,
            "bbox": list(self.bbox),
            "view_angle": view_angle,
            "view_angle_confidence": normalize_confidence(self.view_angle_confidence) if view_angle != "UNKNOWN" else None,
            "angle_images": normalize_angle_images(self.angle_images, VEHICLE_CAPTURE_ANGLES),
        }

    def print_log(self) -> None:
        """Prints the standardized terminal telemetry for this event."""
        print("\n[VEHICLE EVENT]")
        print(f"Track ID: {self.track_id}")
        print(f"Type: {self.vehicle_type}")
        print(f"Direction: {self.direction}")
        print(f"Confidence: {self.confidence:.2f}")
        print(f"Frame: {self.frame_index}")
        print(f"Event ID: {self.event_id}")
        print(f"Timestamp: {self.timestamp}\n")
